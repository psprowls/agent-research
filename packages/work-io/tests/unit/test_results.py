from __future__ import annotations

from work_io.results import render

START_SHA = "a1b2c3d" + "0" * 33
END_SHA = "e5f6a7b" + "1" * 33


def test_render_execute_stub_matches_expected_shape() -> None:
    body = render(
        phase="execute",
        start_sha=START_SHA,
        end_sha=END_SHA,
        files=[
            "packages/work-io/src/work_io/paths.py",
            "packages/work-io/src/work_io/results.py",
        ],
        commits=[
            "a1b2c3d feat(work-io): add results stub renderer",
            "e5f6a7b test(work-io): add results tests",
        ],
    )
    expected = (
        "\n".join(
            [
                "## Execute — results",
                "",
                "**Commits:** `a1b2c3d`..`e5f6a7b` (2 commits)",
                "**Files changed:** 2",
                "",
                "- packages/work-io/src/work_io/paths.py",
                "- packages/work-io/src/work_io/results.py",
                "",
                "- a1b2c3d feat(work-io): add results stub renderer",
                "- e5f6a7b test(work-io): add results tests",
                "",
                "_Mechanical stub, generated by `gw work advance`._",
            ]
        )
        + "\n"
    )
    assert body == expected


def test_render_finish_capitalizes_phase_heading() -> None:
    body = render(phase="finish", start_sha=START_SHA, end_sha=END_SHA, files=[], commits=[])
    assert body.startswith("## Finish — results\n")


def test_render_singular_commit_word() -> None:
    body = render(
        phase="execute",
        start_sha=START_SHA,
        end_sha=END_SHA,
        files=[],
        commits=["a1b2c3d feat(work-io): single commit"],
    )
    assert "(1 commit)" in body
    assert "(1 commits)" not in body


def test_render_zero_commits_uses_plural() -> None:
    body = render(phase="execute", start_sha=START_SHA, end_sha=END_SHA, files=[], commits=[])
    assert "(0 commits)" in body


def test_render_empty_files_and_commits_produces_valid_markdown() -> None:
    body = render(phase="finish", start_sha=START_SHA, end_sha=END_SHA, files=[], commits=[])
    expected = (
        "\n".join(
            [
                "## Finish — results",
                "",
                "**Commits:** `a1b2c3d`..`e5f6a7b` (0 commits)",
                "**Files changed:** 0",
                "",
                "",
                "",
                "_Mechanical stub, generated by `gw work advance`._",
            ]
        )
        + "\n"
    )
    assert body == expected
