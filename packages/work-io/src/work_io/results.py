"""Render the deterministic '## <Phase> — results' stub body for a work
item's execute/finish phase — pure, no I/O. Git-fact gathering and the file
write live in graph_wiki_core.commands.work, next to `_git_head`.
"""

from __future__ import annotations


def render(
    *,
    phase: str,
    start_sha: str,
    end_sha: str,
    files: list[str],
    commits: list[str],
) -> str:
    """Render the mechanical results-stub markdown body.

    `commits` is a list of already-formatted `git log --oneline` lines
    (e.g. "a1b2c3d feat: add renderer"); `files` is a list of file paths
    (already flattened from `git diff --name-status`).
    """
    commit_word = "commit" if len(commits) == 1 else "commits"
    lines = [
        f"## {phase.capitalize()} — results",
        "",
        f"**Commits:** `{start_sha[:7]}`..`{end_sha[:7]}` ({len(commits)} {commit_word})",
        f"**Files changed:** {len(files)}",
        "",
    ]
    lines += [f"- {f}" for f in files]
    lines.append("")
    lines += [f"- {c}" for c in commits]
    lines.append("")
    lines.append("_Mechanical stub, generated by `gw work advance`._")
    return "\n".join(lines) + "\n"
